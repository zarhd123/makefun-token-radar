// Token Radar's model, version radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// pre-token protocol below the watchlist floor that could plausibly launch a token of its own. A
// protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol). Live-token protocols are kept apart and shown with the market's own values, never mixed
// into the ranked board.
//
// Implied value is a comparables model, learned from the snapshot's own figures, never from a
// hand-kept list of names:
//
//   multiple   = median(mcap_usd / tvl_usd) over the live protocols in the same category that
//                record a market cap, when at least 3 of them do; otherwise the median over all
//                live protocols in the snapshot. Clamped to [0.02, 1.0]: a token is never worth
//                more than the value its protocol secures, and never less than two cents per
//                dollar of TVL in this snapshot's market.
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.03 x min(chains - 1, 5)           (at most 1.15: more chains, more surface)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// The same function scores every row. No protocol name is ever special-cased: the only inputs are
// the snapshot's ten fields per protocol, and the medians are computed from the same snapshot.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

